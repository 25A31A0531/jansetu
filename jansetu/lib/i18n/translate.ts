export function translateContent(
  text: string,
  targetLang: SupportedLanguage
): { text: string; isAiTranslation: boolean } {
  if (targetLang === 'en' || !text) {
    return { text, isAiTranslation: false };
  }
  if (phraseDictionary[text]?.[targetLang]) {
    return { text: phraseDictionary[text][targetLang]!, isAiTranslation: false };
  }
  return { text, isAiTranslation: false };
}
